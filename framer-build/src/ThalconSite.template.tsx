// Runs main.js, remembering every listener and observer it sets up so the
// page can be torn down cleanly (Framer remounts components while editing).
function start() {
    const undo = []
    const winAdd = window.addEventListener
    const docAdd = document.addEventListener
    const IO = window.IntersectionObserver
    window.addEventListener = function (...a) {
        undo.push(() => window.removeEventListener(...a))
        return winAdd.apply(this, a)
    }
    document.addEventListener = function (...a) {
        undo.push(() => document.removeEventListener(...a))
        return docAdd.apply(this, a)
    }
    window.IntersectionObserver = class extends IO {
        constructor(...a) {
            super(...a)
            undo.push(() => this.disconnect())
        }
    }
    let alive = true
    const raf = (fn) => (alive ? window.requestAnimationFrame(fn) : 0)
    document.body.classList.add("is-loading")
    try {
        boot({ requestAnimationFrame: raf, createIllo })
    } finally {
        window.addEventListener = winAdd
        document.addEventListener = docAdd
        window.IntersectionObserver = IO
    }
    return () => {
        alive = false
        undo.forEach((fn) => fn())
        document.body.classList.remove("is-loading", "is-intro")
    }
}

