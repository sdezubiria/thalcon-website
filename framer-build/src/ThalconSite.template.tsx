// Framer doesn't keep image defaults inside list items, so a logo left empty
// falls back to the original one for the item with the same name
function withLogos(list, originals) {
    return (list || []).map((item) => {
        if (item?.logo?.src) return item
        const original = originals.find((o) => o.name === item?.name && o.logo)
        return original ? { ...item, logo: original.logo } : item
    })
}

export default function ThalconSite(props) {
    const d = ThalconSite.defaultProps
    const p = { ...d, ...props }
    p.statsImage = p.statsImage?.src ? p.statsImage : d.statsImage
    p.certifications = withLogos(p.certifications, d.certifications)
    p.partners = withLogos(p.partners, d.partners)
    const onCanvas = RenderTarget.current() === RenderTarget.canvas || RenderTarget.current() === RenderTarget.thumbnail
    const html = useMemo(() => renderMarkup(p), [p.stats, p.statsImage, p.certifications, p.partners, p.jobs, p.heroVideo])
    const ref = useRef(null)

    useEffect(() => {
        if (onCanvas) return
        // Start from untouched markup every time: main.js rewrites the DOM
        ref.current.innerHTML = html
        return start()
    }, [html, onCanvas])

    return (
        <div style={{ width: "100%" }}>
            {/* Raw, not as a text child: React would escape the quotes in
                [data-theme="dark"] and content: "" when Framer pre-renders the page */}
            <style dangerouslySetInnerHTML={{ __html: CSS + (onCanvas ? CANVAS_CSS : "") }} />
            <div ref={ref} className="tc-site" dangerouslySetInnerHTML={{ __html: html }} />
        </div>
    )
}

